/**
 * Server-side PDF generators for BenefitsSafe exports.
 *
 * Uses pdfkit. Each builder returns a Buffer containing the complete
 * PDF — we buffer rather than stream because Next.js Route Handlers
 * can consume Buffer bodies directly and the expected report sizes
 * (hundreds, not hundreds of thousands of rows) fit comfortably in
 * memory. If reports grow we can swap to ReadableStream later.
 */

import PDFDocument from "pdfkit";
import type {
  CsvExpenseRow,
  CsvTransactionRow,
  CsvAuditRow,
  CsvLedgerRow,
  CsvGrantRow,
} from "./report-csv";

interface ReportMeta {
  orgName: string;
  title: string;
  periodStart?: Date | null;
  periodEnd?: Date | null;
}

// ═══════════════════════════════════════════════════════════
// Document scaffolding
// ═══════════════════════════════════════════════════════════

function formatDate(d: Date | string | null | undefined): string {
  if (!d) return "—";
  const date = typeof d === "string" ? new Date(d) : d;
  if (Number.isNaN(date.getTime())) return "—";
  return date.toISOString().slice(0, 10);
}

function formatMoney(v: string | number | null | undefined): string {
  if (v === null || v === undefined) return "$0.00";
  const n = typeof v === "number" ? v : parseFloat(String(v));
  if (Number.isNaN(n)) return "$0.00";
  return `$${n.toFixed(2)}`;
}

function fullName(p: { firstName: string; lastName: string } | null | undefined): string {
  if (!p) return "—";
  return `${p.firstName || ""} ${p.lastName || ""}`.trim() || "—";
}

/** Drain a pdfkit document into a single Buffer. */
function collect(doc: PDFKit.PDFDocument): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });
}

function drawHeader(doc: PDFKit.PDFDocument, meta: ReportMeta): void {
  doc
    .fontSize(18)
    .fillColor("#0f172a")
    .text(meta.orgName, { align: "left" });
  doc
    .fontSize(13)
    .fillColor("#475569")
    .text(meta.title);

  const rangeLine =
    meta.periodStart || meta.periodEnd
      ? `Period: ${formatDate(meta.periodStart)} — ${formatDate(meta.periodEnd)}`
      : "";
  if (rangeLine) {
    doc.fontSize(10).fillColor("#64748b").text(rangeLine);
  }
  doc
    .fontSize(10)
    .fillColor("#94a3b8")
    .text(`Generated ${new Date().toISOString()}`);

  doc.moveDown(0.5);
  doc
    .strokeColor("#e2e8f0")
    .lineWidth(1)
    .moveTo(doc.page.margins.left, doc.y)
    .lineTo(doc.page.width - doc.page.margins.right, doc.y)
    .stroke();
  doc.moveDown(0.75);
  doc.fillColor("#0f172a");
}

function drawFooterOnAllPages(doc: PDFKit.PDFDocument, orgName: string): void {
  const range = doc.bufferedPageRange();
  for (let i = 0; i < range.count; i++) {
    doc.switchToPage(range.start + i);
    const bottom = doc.page.height - doc.page.margins.bottom + 15;
    doc
      .fontSize(8)
      .fillColor("#94a3b8")
      .text(
        `Generated by BenefitsSafe for ${orgName} · Confidential`,
        doc.page.margins.left,
        bottom,
        { align: "left", lineBreak: false },
      );
    doc.text(
      `Page ${i + 1} of ${range.count}`,
      doc.page.margins.left,
      bottom,
      {
        align: "right",
        lineBreak: false,
        width: doc.page.width - doc.page.margins.left - doc.page.margins.right,
      },
    );
  }
}

// ═══════════════════════════════════════════════════════════
// Table primitives
// ═══════════════════════════════════════════════════════════

interface TableColumn {
  header: string;
  width: number;
  align?: "left" | "right" | "center";
}

function drawTable(
  doc: PDFKit.PDFDocument,
  columns: TableColumn[],
  rows: string[][],
): void {
  const startX = doc.page.margins.left;
  const rightEdge = doc.page.width - doc.page.margins.right;
  const totalWidth = rightEdge - startX;
  const declaredWidth = columns.reduce((s, c) => s + c.width, 0);
  // Normalize widths to total available
  const scale = totalWidth / declaredWidth;
  const widths = columns.map((c) => c.width * scale);

  const drawHeaderRow = () => {
    let x = startX;
    const y = doc.y;
    doc
      .rect(startX, y - 2, totalWidth, 18)
      .fill("#0f172a");
    doc.fillColor("#ffffff").fontSize(9).font("Helvetica-Bold");
    columns.forEach((c, i) => {
      doc.text(c.header, x + 4, y + 2, {
        width: widths[i] - 8,
        align: c.align || "left",
        lineBreak: false,
        ellipsis: true,
      });
      x += widths[i];
    });
    doc.y = y + 18;
    doc.fillColor("#0f172a").font("Helvetica");
  };

  drawHeaderRow();

  rows.forEach((row, rowIdx) => {
    // Page break if near bottom
    if (doc.y > doc.page.height - doc.page.margins.bottom - 40) {
      doc.addPage();
      drawHeaderRow();
    }

    const rowY = doc.y;
    const rowHeight = 16;
    if (rowIdx % 2 === 1) {
      doc
        .rect(startX, rowY - 1, totalWidth, rowHeight)
        .fill("#f8fafc");
    }
    doc.fillColor("#0f172a").fontSize(9).font("Helvetica");

    let x = startX;
    row.forEach((cell, i) => {
      doc.text(cell, x + 4, rowY + 2, {
        width: widths[i] - 8,
        align: columns[i].align || "left",
        lineBreak: false,
        ellipsis: true,
      });
      x += widths[i];
    });

    doc.y = rowY + rowHeight;
  });

  doc.moveDown(0.5);
}

function sectionTitle(doc: PDFKit.PDFDocument, title: string): void {
  doc.moveDown(0.5);
  doc
    .fontSize(12)
    .fillColor("#0f172a")
    .font("Helvetica-Bold")
    .text(title);
  doc.font("Helvetica").moveDown(0.25);
}

// ═══════════════════════════════════════════════════════════
// Report builders
// ═══════════════════════════════════════════════════════════

function buildBaseDoc(meta: ReportMeta): PDFKit.PDFDocument {
  const doc = new PDFDocument({
    size: "LETTER",
    margin: 50,
    bufferPages: true,
    info: {
      Title: meta.title,
      Author: `BenefitsSafe — ${meta.orgName}`,
      Creator: "BenefitsSafe",
    },
  });
  drawHeader(doc, meta);
  return doc;
}

async function finalizeDoc(
  doc: PDFKit.PDFDocument,
  orgName: string,
): Promise<Buffer> {
  drawFooterOnAllPages(doc, orgName);
  doc.end();
  return collect(doc);
}

export async function generateExpenseSummaryPDF(input: {
  meta: ReportMeta;
  expenses: CsvExpenseRow[];
}): Promise<Buffer> {
  const doc = buildBaseDoc(input.meta);

  sectionTitle(doc, `Expenses (${input.expenses.length})`);

  if (input.expenses.length === 0) {
    doc.fontSize(10).fillColor("#64748b").text("No expenses in this period.");
  } else {
    drawTable(
      doc,
      [
        { header: "Date", width: 60 },
        { header: "Description", width: 160 },
        { header: "Grant", width: 100 },
        { header: "Category", width: 80 },
        { header: "Status", width: 60 },
        { header: "Amount", width: 60, align: "right" },
      ],
      input.expenses.map((e) => [
        formatDate(e.createdAt),
        e.description || "—",
        e.grant?.name || "—",
        e.category?.name || "—",
        e.status,
        formatMoney(e.amount),
      ]),
    );

    const total = input.expenses.reduce(
      (s, e) => s + (typeof e.amount === "number" ? e.amount : parseFloat(String(e.amount)) || 0),
      0,
    );
    doc.moveDown(0.5);
    doc
      .fontSize(10)
      .fillColor("#0f172a")
      .font("Helvetica-Bold")
      .text(`Total: ${formatMoney(total)}`, { align: "right" });
    doc.font("Helvetica");
  }

  return finalizeDoc(doc, input.meta.orgName);
}

export async function generateTransactionHistoryPDF(input: {
  meta: ReportMeta;
  transactions: CsvTransactionRow[];
}): Promise<Buffer> {
  const doc = buildBaseDoc(input.meta);

  sectionTitle(doc, `Transactions (${input.transactions.length})`);

  if (input.transactions.length === 0) {
    doc.fontSize(10).fillColor("#64748b").text("No transactions in this period.");
  } else {
    drawTable(
      doc,
      [
        { header: "Date", width: 70 },
        { header: "Merchant", width: 140 },
        { header: "MCC", width: 50 },
        { header: "Card", width: 100 },
        { header: "Status", width: 60 },
        { header: "Amount", width: 60, align: "right" },
      ],
      input.transactions.map((t) => [
        formatDate(t.createdAt),
        t.merchantName || "—",
        t.merchantCategory || "—",
        t.card ? `${t.card.cardLabel || "Card"} ••${t.card.last4}` : "—",
        t.status,
        formatMoney(t.amount),
      ]),
    );
  }

  return finalizeDoc(doc, input.meta.orgName);
}

export async function generateAuditTrailPDF(input: {
  meta: ReportMeta;
  logs: CsvAuditRow[];
}): Promise<Buffer> {
  const doc = buildBaseDoc(input.meta);

  sectionTitle(doc, `Audit Log Entries (${input.logs.length})`);

  if (input.logs.length === 0) {
    doc.fontSize(10).fillColor("#64748b").text("No audit log entries in this period.");
  } else {
    drawTable(
      doc,
      [
        { header: "Timestamp", width: 120 },
        { header: "Action", width: 80 },
        { header: "Entity", width: 90 },
        { header: "Entity ID", width: 120 },
        { header: "User", width: 100 },
      ],
      input.logs.map((l) => [
        (typeof l.createdAt === "string" ? l.createdAt : l.createdAt.toISOString()).replace("T", " ").slice(0, 19),
        l.action,
        l.entityType,
        l.entityId,
        fullName(l.user),
      ]),
    );
  }

  return finalizeDoc(doc, input.meta.orgName);
}

