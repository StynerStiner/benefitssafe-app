export async function generateGrantCompliancePDF(input: {
  meta: ReportMeta;
  grant: CsvGrantRow & { approvedMCCs?: unknown; blockedMCCs?: unknown; description?: string | null };
  expenses: CsvExpenseRow[];
  transactions: CsvTransactionRow[];
}): Promise<Buffer> {
  const { grant, expenses, transactions } = input;
  const doc = buildBaseDoc(input.meta);

  const totalBudget = parseFloat(String(grant.totalAmount)) || 0;
  const spent = parseFloat(String(grant.spentAmount)) || 0;
  const remaining = parseFloat(String(grant.remainingAmount)) || 0;
  const utilization = totalBudget > 0 ? (spent / totalBudget) * 100 : 0;

  // Summary block
  sectionTitle(doc, "Grant Summary");
  const summaryRows: [string, string][] = [
    ["Grant Name", grant.name],
    ["Status", grant.status],
    ["Beneficiary", fullName(grant.beneficiary)],
    ["Start Date", formatDate(grant.startDate)],
    ["End Date", formatDate(grant.endDate)],
    ["Total Budget", formatMoney(grant.totalAmount)],
    ["Spent", formatMoney(grant.spentAmount)],
    ["Remaining", formatMoney(grant.remainingAmount)],
    ["Utilization", `${utilization.toFixed(1)}%`],
  ];
  doc.fontSize(10).fillColor("#0f172a");
  summaryRows.forEach(([k, v]) => {
    doc.font("Helvetica-Bold").text(`${k}: `, { continued: true });
    doc.font("Helvetica").text(v);
  });

  // MCC rules
  const approved = Array.isArray(grant.approvedMCCs) ? (grant.approvedMCCs as string[]) : [];
  const blocked = Array.isArray(grant.blockedMCCs) ? (grant.blockedMCCs as string[]) : [];
  if (approved.length || blocked.length) {
    doc.moveDown(0.5);
    if (approved.length) {
      doc.font("Helvetica-Bold").text("Approved MCCs: ", { continued: true });
      doc.font("Helvetica").text(approved.join(", "));
    }
    if (blocked.length) {
      doc.font("Helvetica-Bold").text("Blocked MCCs: ", { continued: true });
      doc.font("Helvetica").text(blocked.join(", "));
    }
  }

  // Remaining flagged? (just a heuristic — high utilization)
  if (remaining < 0) {
    doc.moveDown(0.5);
    doc.fillColor("#b91c1c").font("Helvetica-Bold").text(
      `⚠ Overspent by ${formatMoney(Math.abs(remaining))}`,
    );
    doc.fillColor("#0f172a").font("Helvetica");
  }

  // Expenses section
  sectionTitle(doc, `Expenses (${expenses.length})`);
  if (expenses.length === 0) {
    doc.fontSize(10).fillColor("#64748b").text("No expenses recorded for this grant.");
  } else {
    drawTable(
      doc,
      [
        { header: "Date", width: 60 },
        { header: "Description", width: 180 },
        { header: "Category", width: 80 },
        { header: "Status", width: 60 },
        { header: "Risk", width: 60 },
        { header: "Amount", width: 60, align: "right" },
      ],
      expenses.map((e) => [
        formatDate(e.createdAt),
        e.description || "—",
        e.category?.name || "—",
        e.status,
        e.riskClassification || "—",
        formatMoney(e.amount),
      ]),
    );
  }

  // Transactions section
  sectionTitle(doc, `Transactions (${transactions.length})`);
  if (transactions.length === 0) {
    doc.fontSize(10).fillColor("#64748b").text("No card transactions for this grant.");
  } else {
    drawTable(
      doc,
      [
        { header: "Date", width: 70 },
        { header: "Merchant", width: 160 },
        { header: "MCC", width: 50 },
        { header: "Status", width: 60 },
        { header: "Amount", width: 60, align: "right" },
      ],
      transactions.map((t) => [
        formatDate(t.createdAt),
        t.merchantName || "—",
        t.merchantCategory || "—",
        t.status,
        formatMoney(t.amount),
      ]),
    );
  }

  return finalizeDoc(doc, input.meta.orgName);
}
